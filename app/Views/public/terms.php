        <h2>§ 17. Reklamacje dotyczące funkcjonowania Serwisu</h2>
        <p>Reklamacje dotyczące funkcjonowania Serwisu mogą być składane drogą elektroniczną na adres e-mail właściciela Serwisu.</p>
        <p>Reklamacja powinna zawierać w szczególności:</p>
        <ul>
            <li>imię i nazwisko osoby zgłaszającej,</li>
            <li>adres e-mail do kontaktu,</li>
            <li>opis problemu,</li>
            <li>datę wystąpienia problemu,</li>
            <li>żądanie zgłaszającego.</li>
        </ul>
        <p>Jeżeli do rozpatrzenia reklamacji niezbędne będzie uzupełnienie informacji, Usługodawca może zwrócić się do zgłaszającego o ich przekazanie.</p>
        <p>Reklamacje rozpatrywane są bez zbędnej zwłoki, nie później niż w terminie 14 dni od dnia ich otrzymania.</p>
        <p>Termin może ulec wydłużeniu, jeżeli charakter sprawy wymaga uzyskania dodatkowych informacji lub wyjaśnień. O takim przedłużeniu zgłaszający zostanie poinformowany.</p>

        <h2>§ 18. Reklamacje dotyczące biletów</h2>
        <p>IntegracjaStudencka.pl nie rozpatruje reklamacji dotyczących:</p>
        <ul>
            <li>zakupu biletów,</li>
            <li>płatności,</li>
            <li>zwrotów,</li>
            <li>faktur,</li>
            <li>błędnych danych na bilecie,</li>
            <li>niedostarczenia biletu,</li>
            <li>problemów technicznych systemów sprzedaży biletów.</li>
        </ul>
        <p>Reklamacje wskazane w ust. 1 należy kierować bezpośrednio do operatora sprzedaży biletów, za pośrednictwem którego dokonano zakupu.</p>
        <p>Na dzień wejścia w życie niniejszego Regulaminu operatorami sprzedaży są w szczególności:</p>
        <ul>
            <li>KupBilecik.pl,</li>
            <li>Stage24.pl.</li>
        </ul>
        <p>W przypadku nawiązania współpracy z kolejnymi operatorami sprzedaży biletów reklamacje należy kierować do właściwego operatora wskazanego przy danym wydarzeniu.</p>
        <p>IntegracjaStudencka.pl nie posiada dostępu do danych transakcyjnych operatorów sprzedaży i nie ma możliwości ingerowania w proces sprzedaży, płatności ani dostarczania biletów.</p>

        <h2>§ 19. Prawa własności intelektualnej</h2>
        <p>Wszelkie prawa do Serwisu, w tym w szczególności do jego:</p>
        <ul>
            <li>nazwy,</li>
            <li>logotypów,</li>
            <li>znaków graficznych,</li>
            <li>szaty graficznej,</li>
            <li>kodu źródłowego,</li>
            <li>układu strony,</li>
            <li>tekstów,</li>
            <li>zdjęć,</li>
            <li>filmów,</li>
            <li>grafik,</li>
            <li>baz danych,</li>
            <li>materiałów reklamowych,</li>
            <li>materiałów promocyjnych.</li>
        </ul>
        <p>Przysługują Usługodawcy albo podmiotom, z którymi Usługodawca współpracuje na podstawie stosownych umów lub obowiązujących przepisów prawa.</p>
        <p>Korzystanie z materiałów zamieszczonych w Serwisie nie oznacza nabycia jakichkolwiek praw do tych materiałów.</p>
        <p>Zabrania się bez uprzedniej pisemnej zgody Usługodawcy:</p>
        <ul>
            <li>kopiowania treści Serwisu,</li>
            <li>publikowania materiałów w innych serwisach internetowych,</li>
            <li>wykorzystywania zdjęć,</li>
            <li>wykorzystywania grafik,</li>
            <li>wykorzystywania logotypów,</li>
            <li>kopiowania opisów wydarzeń,</li>
            <li>wykorzystywania materiałów reklamowych w celach komercyjnych.</li>
        </ul>
        <p>Dozwolone jest udostępnianie linków prowadzących do Serwisu, o ile nie narusza to dobrego imienia Serwisu ani obowiązujących przepisów prawa.</p>

        <h2>§ 20. Dane osobowe</h2>
        <p>Administratorem danych osobowych przetwarzanych w związku z korzystaniem z Serwisu jest właściciel Serwisu.</p>
        <p>Dane osobowe przetwarzane są zgodnie z:</p>
        <ul>
            <li>Rozporządzeniem Parlamentu Europejskiego i Rady (UE) 2016/679 (RODO),</li>
            <li>ustawą o świadczeniu usług drogą elektroniczną,</li>
            <li>ustawą Prawo komunikacji elektronicznej,</li>
            <li>innymi obowiązującymi przepisami prawa.</li>
        </ul>
        <p>Szczegółowe zasady przetwarzania danych osobowych określa Polityka Prywatności dostępna w Serwisie.</p>
        <p>Dane osobowe mogą być przetwarzane między innymi w celu:</p>
        <ul>
            <li>udzielania odpowiedzi na wiadomości,</li>
            <li>realizacji usług świadczonych drogą elektroniczną,</li>
            <li>przesyłania newslettera,</li>
            <li>informowania o wydarzeniach,</li>
            <li>prowadzenia statystyk,</li>
            <li>zapewnienia bezpieczeństwa Serwisu,</li>
            <li>dochodzenia lub obrony przed roszczeniami.</li>
        </ul>
        <p>Serwis może wykorzystywać pliki cookies oraz podobne technologie zgodnie z Polityką Prywatności.</p>

        <h2>§ 21. Ograniczenie odpowiedzialności</h2>
        <p>Usługodawca dokłada należytej staranności, aby informacje publikowane w Serwisie były aktualne i rzetelne.</p>
        <p>Pomimo zachowania należytej staranności Usługodawca nie gwarantuje, że wszystkie informacje publikowane przez Organizatorów są wolne od błędów lub pozostaną aktualne.</p>
        <p>Usługodawca nie ponosi odpowiedzialności za szkody wynikające z:</p>
        <ul>
