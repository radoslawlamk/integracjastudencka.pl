            <li>zdjęcia,</li>
            <li>materiały promocyjne,</li>
            <li>ceny biletów,</li>
            <li>link do operatora sprzedaży,</li>
            <li>informacje o ograniczeniach wiekowych,</li>
            <li>informacje organizacyjne.</li>
        </ul>
        <p>Usługodawca dokłada należytej staranności, aby informacje były aktualne.</p>
