            <li>korzystania z Serwisu niezgodnie z Regulaminem,</li>
            <li>działania osób trzecich,</li>
            <li>awarii sieci Internet,</li>
            <li>działania operatorów telekomunikacyjnych,</li>
            <li>działania operatorów sprzedaży biletów,</li>
            <li>działania Organizatorów wydarzeń,</li>
            <li>działania partnerów handlowych,</li>
            <li>siły wyższej.</li>
        </ul>
        <p>Serwis może zawierać błędy techniczne, literówki lub omyłki redakcyjne, które mogą być usuwane bez wcześniejszego powiadamiania Użytkowników.</p>
        <p>Usługodawca zastrzega sobie prawo do:</p>
        <ul>
            <li>czasowego zawieszenia działania Serwisu,</li>
            <li>zmiany wyglądu Serwisu,</li>
            <li>zmiany funkcjonalności,</li>
            <li>dodawania nowych usług,</li>
            <li>usuwania wybranych funkcjonalności,</li>
            <li>zmiany partnerów handlowych,</li>
            <li>zmiany operatorów sprzedaży biletów,</li>
            <li>zakończenia współpracy z wybranymi partnerami.</li>
        </ul>

