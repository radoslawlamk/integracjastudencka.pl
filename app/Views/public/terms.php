        <p>Użytkownik zobowiązuje się korzystać z Serwisu zgodnie z:</p>
        <ul>
            <li>obowiązującymi przepisami prawa,</li>
            <li>niniejszym Regulaminem,</li>
            <li>zasadami współżycia społecznego,</li>
            <li>dobrymi obyczajami.</li>
        </ul>
        <p>Zabrania się korzystania z Serwisu w sposób mogący:</p>
        <ul>
            <li>zakłócać jego funkcjonowanie,</li>
            <li>naruszać prawa innych osób,</li>
            <li>powodować przeciążenie infrastruktury informatycznej,</li>
            <li>naruszać bezpieczeństwo Serwisu.</li>
        </ul>
        <p>Zabrania się dostarczania za pośrednictwem Serwisu treści:</p>
        <ul>
            <li>bezprawnych,</li>
            <li>obraźliwych,</li>
            <li>wulgarnych,</li>
            <li>dyskryminujących,</li>
            <li>naruszających dobra osobiste osób trzecich,</li>
            <li>zawierających wirusy komputerowe lub inne złośliwe oprogramowanie.</li>
        </ul>
        <p>Użytkownik ponosi odpowiedzialność za treści przesyłane za pośrednictwem formularzy dostępnych w Serwisie.</p>
        <p>Usługodawca może odmówić realizacji zgłoszenia lub usunąć przesłane treści naruszające Regulamin albo przepisy prawa.</p>

