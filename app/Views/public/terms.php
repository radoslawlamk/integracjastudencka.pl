        <p>IntegracjaStudencka.pl odpowiada wyłącznie za prawidłowe funkcjonowanie Serwisu jako platformy internetowej.</p>
        <p>Usługodawca nie ponosi odpowiedzialności za:</p>
        <ul>
            <li>przebieg wydarzeń,</li>
            <li>zachowanie uczestników,</li>
            <li>działania Organizatora,</li>
            <li>działania operatorów sprzedaży biletów,</li>
            <li>decyzje klubów, lokali lub właścicieli obiektów,</li>
            <li>odmowę wstępu na wydarzenie z przyczyn leżących po stronie uczestnika,</li>
            <li>brak dostępności biletów,</li>
            <li>błędy systemów sprzedaży biletów,</li>
            <li>opóźnienia w dostarczeniu biletów,</li>
            <li>błędy operatorów płatności,</li>
            <li>awarie systemów partnerów,</li>
            <li>szkody wynikające z działania siły wyższej.</li>
        </ul>
        <p>IntegracjaStudencka.pl nie odpowiada za treści publikowane na stronach internetowych partnerów, do których prowadzą linki zamieszczone w Serwisie.</p>
        <p>Przejście na stronę partnera oznacza korzystanie z serwisu prowadzonego przez niezależny podmiot, który działa na podstawie własnego regulaminu i polityki prywatności.</p>

        <h2>§ 13. Zasady uczestnictwa w wydarzeniach</h2>
        <p>Warunki uczestnictwa w danym wydarzeniu określa jego Organizator.</p>
        <p>Informacje dotyczące wydarzenia publikowane w Serwisie mają charakter informacyjny i nie zastępują regulaminu Organizatora.</p>
        <p>Uczestnik zobowiązany jest do przestrzegania:</p>
        <ul>
            <li>regulaminu Organizatora,</li>
            <li>regulaminu obiektu, w którym odbywa się wydarzenie,</li>
            <li>poleceń służb porządkowych, ochrony oraz osób upoważnionych przez Organizatora,</li>
            <li>obowiązujących przepisów prawa.</li>
        </ul>
        <p>Organizator może uzależnić udział w wydarzeniu od spełnienia określonych warunków, w szczególności:</p>
        <ul>
            <li>osiągnięcia określonego wieku,</li>
            <li>posiadania ważnego biletu,</li>
            <li>okazania dokumentu tożsamości,</li>
            <li>spełnienia wymogów bezpieczeństwa.</li>
        </ul>
        <p>Informacja o ograniczeniach wiekowych publikowana przy wydarzeniu ma charakter orientacyjny. Ostateczną decyzję o dopuszczeniu uczestnika do wydarzenia podejmuje Organizator lub obsługa obiektu.</p>
        <p>IntegracjaStudencka.pl nie odpowiada za decyzje Organizatora dotyczące wpuszczenia lub niewpuszczenia uczestnika na wydarzenie.</p>

        <h2>§ 14. Zachowanie uczestników</h2>
        <p>Każdy uczestnik wydarzenia zobowiązany jest do zachowywania się w sposób zgodny z przepisami prawa oraz zasadami współżycia społecznego.</p>
        <p>Zabrania się w szczególności:</p>
        <ul>
            <li>stosowania przemocy fizycznej lub psychicznej,</li>
            <li>zachowań agresywnych,</li>
            <li>nękania innych uczestników,</li>
            <li>naruszania dóbr osobistych innych osób,</li>
            <li>niszczenia mienia,</li>
            <li>zakłócania przebiegu wydarzenia,</li>
            <li>wnoszenia przedmiotów zabronionych przez Organizatora,</li>
            <li>podejmowania działań zagrażających bezpieczeństwu innych osób.</li>
        </ul>
        <p>Organizator może odmówić wstępu lub usunąć z wydarzenia osobę naruszającą obowiązujące przepisy lub regulamin wydarzenia.</p>
        <p>W przypadku usunięcia uczestnika z przyczyn leżących po jego stronie, IntegracjaStudencka.pl nie ponosi odpowiedzialności za skutki takiej decyzji.</p>

