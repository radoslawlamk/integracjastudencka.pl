        <ul>
            <li>urządzenia z dostępem do Internetu,</li>
            <li>aktualnej przeglądarki internetowej obsługującej technologie HTML5, CSS oraz JavaScript,</li>
            <li>aktywnego adresu poczty elektronicznej – w przypadku korzystania z formularzy kontaktowych lub zapisów na powiadomienia,</li>
            <li>urządzenia umożliwiającego wyświetlanie stron internetowych.</li>
        </ul>
        <p>Usługodawca dokłada należytej staranności, aby Serwis działał w sposób ciągły i prawidłowy, jednak nie gwarantuje nieprzerwanej dostępności Serwisu.</p>
        <p>Mogą występować czasowe przerwy w działaniu Serwisu wynikające w szczególności z:</p>
        <ul>
            <li>prac serwisowych,</li>
            <li>modernizacji,</li>
            <li>aktualizacji oprogramowania,</li>
            <li>awarii infrastruktury teleinformatycznej,</li>
            <li>działania siły wyższej,</li>
