        <h2>§ 1. Postanowienia ogólne</h2>
        <p>Niniejszy Regulamin określa zasady korzystania z serwisu internetowego dostępnego pod adresem www.integracjastudencka.pl, zwanego dalej „Serwisem”.</p>
        <p>Regulamin określa w szczególności:</p>
        <ul>
            <li>zasady korzystania z Serwisu,</li>
            <li>zasady świadczenia usług drogą elektroniczną,</li>
            <li>zasady korzystania z formularzy dostępnych w Serwisie,</li>
            <li>zasady publikowania oraz promowania wydarzeń studenckich,</li>
            <li>zasady przekierowania Użytkowników do zewnętrznych platform sprzedaży biletów,</li>
            <li>zasady odpowiedzialności za treści publikowane w Serwisie,</li>
            <li>zasady składania reklamacji dotyczących funkcjonowania Serwisu,</li>
            <li>prawa i obowiązki Użytkowników oraz właściciela Serwisu.</li>
        </ul>
        <p>Właścicielem oraz operatorem Serwisu jest:</p>
        <p><strong>StudenciPolska.pl oraz IntegracjaStudencka.pl</strong></p>
        <p>zwany dalej Usługodawcą.</p>
        <p>Regulamin udostępniany jest nieodpłatnie w Serwisie w sposób umożliwiający jego pobranie, zapisanie oraz wydrukowanie.</p>
        <p>Rozpoczęcie korzystania z Serwisu oznacza akceptację niniejszego Regulaminu.</p>
        <p>Korzystanie z Serwisu odbywa się zgodnie z obowiązującymi przepisami prawa polskiego.</p>

        <h2>§ 2. Definicje</h2>
        <p>Na potrzeby Regulaminu przyjmuje się następujące znaczenie pojęć:</p>
        <p><strong>Serwis</strong> – portal internetowy dostępny pod adresem www.integracjastudencka.pl.</p>
        <p><strong>Usługodawca</strong> – właściciel Serwisu.</p>
        <p><strong>Użytkownik</strong> – każda osoba odwiedzająca Serwis.</p>
        <p><strong>Organizator</strong> – podmiot organizujący dane wydarzenie publikowane w Serwisie.</p>
        <p><strong>Partner</strong> – podmiot współpracujący z Serwisem przy promocji wydarzeń, sprzedaży biletów lub świadczeniu innych usług.</p>
        <p><strong>Operator sprzedaży biletów</strong> – zewnętrzny podmiot prowadzący sprzedaż biletów na wydarzenia prezentowane w Serwisie.</p>
        <p>Na dzień wejścia w życie Regulaminu operatorami sprzedaży są w szczególności:</p>
        <ul>
            <li>KupBilecik.pl</li>
            <li>Stage24.pl</li>
        </ul>
        <p>Lista operatorów może ulegać zmianom i być rozszerzana bez konieczności zmiany niniejszego Regulaminu.</p>
        <p><strong>Wydarzenie</strong> – impreza, koncert, wydarzenie studenckie, integracyjne, klubowe, sportowe, kulturalne lub inne wydarzenie publikowane w Serwisie.</p>
        <p><strong>Bilet</strong> – dokument elektroniczny lub papierowy uprawniający do udziału w wydarzeniu, sprzedawany przez operatora sprzedaży biletów.</p>

        <h2>§ 3. Charakter Serwisu</h2>
        <p>IntegracjaStudencka.pl jest portalem internetowym o charakterze informacyjnym, promocyjnym oraz marketingowym.</p>
        <p>Celem Serwisu jest prezentowanie wydarzeń skierowanych przede wszystkim do studentów oraz osób pełnoletnich zainteresowanych uczestnictwem w wydarzeniach.</p>
        <p>Serwis umożliwia w szczególności:</p>
        <ul>
            <li>prezentację wydarzeń,</li>
            <li>publikację opisów wydarzeń,</li>
            <li>publikację zdjęć oraz materiałów promocyjnych,</li>
            <li>udostępnianie harmonogramów wydarzeń,</li>
            <li>przekierowanie do zewnętrznych platform sprzedaży biletów,</li>
            <li>kontakt z organizatorami lub właścicielem Serwisu,</li>
            <li>zapis do newslettera lub powiadomień o nowych wydarzeniach, jeżeli funkcjonalność jest dostępna.</li>
        </ul>
        <p>Serwis nie prowadzi sprzedaży alkoholu.</p>
        <p>Serwis nie świadczy usług gastronomicznych.</p>
        <p>Serwis nie organizuje transportu uczestników.</p>
        <p>Korzystanie z Serwisu jest bezpłatne.</p>

        <h2>§ 4. Sprzedaż biletów</h2>
        <p>IntegracjaStudencka.pl nie prowadzi sprzedaży biletów we własnym imieniu.</p>
        <p>Serwis pełni wyłącznie funkcję informacyjną oraz promocyjną.</p>
        <p>Zakup biletu odbywa się bezpośrednio u operatora sprzedaży wskazanego przy danym wydarzeniu.</p>
        <p>Umowa sprzedaży biletu zawierana jest pomiędzy kupującym a operatorem sprzedaży biletów albo organizatorem wydarzenia zgodnie z regulaminem obowiązującym u danego operatora.</p>
        <p>IntegracjaStudencka.pl nie jest stroną umowy sprzedaży biletu.</p>
        <p>Przekierowanie z Serwisu na stronę operatora sprzedaży biletów oznacza opuszczenie Serwisu i przejście do serwisu prowadzonego przez odrębny podmiot.</p>
        <p>Zakup biletu odbywa się zgodnie z regulaminem operatora sprzedaży biletów.</p>
        <p>Aktualni partnerzy sprzedaży biletów to między innymi:</p>
        <ul>
            <li>KupBilecik.pl</li>
            <li>Stage24.pl</li>
        </ul>
        <p>Lista partnerów może ulegać zmianom.</p>

        <h2>§ 5. Reklamacje dotyczące sprzedaży biletów</h2>
        <p>Wszelkie reklamacje dotyczące:</p>
        <ul>
            <li>zakupu biletu,</li>
            <li>płatności,</li>
            <li>zwrotów środków,</li>
            <li>faktur,</li>
            <li>błędnie wystawionych biletów,</li>
            <li>zmiany danych na bilecie,</li>
            <li>braku otrzymania biletu na adres e-mail,</li>
            <li>problemów z płatnością,</li>
            <li>anulowania transakcji,</li>
            <li>realizacji płatności,</li>
        </ul>
        <p>powinny być kierowane bezpośrednio do operatora sprzedaży biletów, u którego dokonano zakupu.</p>
        <p>IntegracjaStudencka.pl nie ma dostępu do systemów sprzedaży operatorów biletowych.</p>
        <p>IntegracjaStudencka.pl nie posiada możliwości:</p>
        <ul>
            <li>wysyłania zakupionych biletów,</li>
            <li>ponownego przesyłania biletów,</li>
            <li>dokonywania zwrotów,</li>
            <li>wystawiania faktur,</li>
            <li>zmiany danych nabywcy,</li>
            <li>anulowania transakcji.</li>
        </ul>
        <p>W sprawach wskazanych powyżej wyłączną odpowiedzialność ponosi operator sprzedaży biletów lub organizator wydarzenia zgodnie z obowiązującymi regulaminami.</p>

        <h2>§ 6. Wymagania techniczne</h2>
